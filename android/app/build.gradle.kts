// Only apply the Google Services plugin once google-services.json has
// actually been added to this directory — applying it unconditionally
// makes every Android build fail immediately when that file is missing.
// Push notifications simply stay disabled (the Dart side already guards
// Firebase.initializeApp() in a try-catch) until the file is dropped in,
// at which point the next build picks this up automatically.
if (file("google-services.json").exists()) {
    apply(plugin = "com.google.gms.google-services")
}

